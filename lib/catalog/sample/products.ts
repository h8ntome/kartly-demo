import type { Category, StoreId, Unit } from "@/lib/types";

/**
 * Canonical Karachi grocery catalogue.
 *
 * `base` is the reference pack price, in PKR, for `defaultQuantity` of the
 * product at a store priced at index 1.00. Per-store prices are derived from
 * it deterministically (see `generate.ts`). Every resulting figure is
 * illustrative sample data — none of it is scraped from, supplied by, or
 * endorsed by the stores named in this app.
 *
 * `packs` lists the pack sizes stores actually sell. Comparing a 1 kg pack
 * against a 5 kg pack on shelf price would be dishonest, so the engine always
 * converts to price-per-base-unit before it decides what is cheapest.
 */
export interface ProductSeed {
  id: string;
  name: string;
  category: Category;
  unit: Unit;
  defaultQuantity: number;
  base: number;
  glyph: string;
  aliases: string[];
  brands: string[];
  /** Pack variants. `index` nudges price-per-unit for bulk vs small packs. */
  packs: { quantity: number; index?: number }[];
  /** Only these stores stock it at all. */
  only?: StoreId[];
  /** These stores never stock it. */
  skip?: StoreId[];
  /** Cheaper swaps worth suggesting when this line dominates a basket. */
  swapIds?: string[];
  swapNote?: string;
}

